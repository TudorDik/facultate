/*
	my_strdup - Custom implementation of strdup.
	Allocates memory for a copy of string 's' and copies it.
*/
char *my_strdup(char *s)
{
	int len;
	char *copy;

	if (!s)
		return NULL;
	len = (int)strlen(s) + 1; /* +1 for null terminator */
	copy = malloc(len * sizeof(char));
	if (copy)
		memcpy(copy, s, len);
	return copy;
}

/*
	create_queue - Allocates a new empty queue.
	Initializes front and rear pointers to NULL.
*/
queue *create_queue(void)
{
	queue *q = malloc(sizeof(queue));

	if (!q)
		exit(1);
	q->front = NULL;
	q->rear = NULL;
	return q;
}

/*
	is_queue_empty - Checks if the queue has any elements.
	Returns true if front is NULL, false otherwise.
*/
bool is_queue_empty(queue *q)
{
	if (!q->front)
		return true;
	return false;
}

/*
	enqueue - Adds a new string to the rear of the queue.
	Handles allocation of a new node and updating pointers.
*/
void enqueue(queue *q, char *text)
{
	node *new_node = malloc(sizeof(node));

	if (!new_node)
		return;
	new_node->data = my_strdup(text); /* Duplicate string to own memory */
	new_node->next = NULL;
	if (!q->rear) {
		q->front = new_node;
		q->rear = new_node;
	} else {
		q->rear->next = new_node;
		q->rear = new_node;
	}
}

/*
	dequeue - Removes and returns the string from the front of the queue.
	Updates front pointer to the next node.
*/
char *dequeue(queue *q)
{
	node *temp;
	char *result;

	if (is_queue_empty(q))
		return NULL;
	temp = q->front;
	result = temp->data;
	q->front = q->front->next;
	if (!q->front)
		q->rear = NULL; /* Queue is now empty */
	free(temp);
	return result;
}

/*
	destroy_queue - Frees the queue and all its data.
	Loops through dequeueing until empty, then frees the queue struct itself.
*/
void destroy_queue(queue *q)
{
	char *data;

	while (!is_queue_empty(q)) {
		data = dequeue(q);
		free(data);
	}
	free(q);
}

/*
	tokenize_command_line - Splits input line into tokens.
	Uses strtok with space, tab, carriage return, and newline delimiters.
*/
void tokenize_command_line(queue *q, char *line)
{
	char *token;
	char *delimiters = " \t\r\n";

	token = strtok(line, delimiters);
	while (token) {
		enqueue(q, token);
		token = strtok(NULL, delimiters);
	}
}

/*
	create_copy_of_image - Deep copies an image structure.
	Allocates new memory for the image structure and its pixel buffer.
*/
image *create_copy_of_image(image *source)
{
	image *new_img;

	if (!source)
		return NULL;
	new_img = malloc(sizeof(image));
	if (!new_img)
		exit(1);
	new_img->width = source->width;
	new_img->height = source->height;
	new_img->max_val = source->max_val;
	new_img->pixels = malloc(new_img->height * sizeof(pixel *));
	for (int i = 0; i < new_img->height; i++) {
		new_img->pixels[i] = malloc(new_img->width * sizeof(pixel));
		/* Use memcpy for fast copying of a row of pixels */
		memcpy(new_img->pixels[i], source->pixels[i],
			   new_img->width * sizeof(pixel));
	}
	return new_img;
}

/*
	destroy_image - Frees all memory for an image.
	Frees each row of pixels, then the array of row pointers, then the struct.
*/
void destroy_image(image *img)
{
	if (!img)
		return;
	for (int i = 0; i < img->height; i++)
		free(img->pixels[i]);
	free(img->pixels);
	free(img);
}

/*
	load_ppm_file - Loads a P6 PPM image from disk.
	Parses the header (P6, width, height, max_val) and reads pixel data.
*/
image *load_ppm_file(char *filename)
{
	FILE *f;
	char *buf;
	int w, h, max;
	image *img;

	f = fopen(filename, "rb");
	if (!f)
		return NULL;

	buf = malloc(256 * sizeof(char));
	if (!buf) {
		fclose(f);
		return NULL;
	}

	if (!fgets(buf, 256, f)) {
		free(buf);
		fclose(f);
		return NULL;
	}
	if (fscanf(f, "%d %d", &w, &h) != 2) {
		/* ignore */
	}
	if (fscanf(f, "%d", &max) != 1) {
		/* ignore */
	}
	fgetc(f);
	free(buf);

	img = malloc(sizeof(image));
	img->width = w;
	img->height = h;
	img->max_val = max;
	img->pixels = malloc(h * sizeof(pixel *));
	for (int i = 0; i < h; i++) {
		img->pixels[i] = malloc(w * sizeof(pixel));
		for (int j = 0; j < w; j++) {
			fread(&img->pixels[i][j].r, 1, 1, f);
			fread(&img->pixels[i][j].g, 1, 1, f);
			fread(&img->pixels[i][j].b, 1, 1, f);
		}
	}
	fclose(f);
	return img;
}

/*
	save_ppm_file - Saves an image to disk in P6 format.
	Writes the header and then dumps the pixel data.
*/
void save_ppm_file(char *filename, image *img)
{
	FILE *f;

	if (!img)
		return;
	f = fopen(filename, "wb");
	if (!f)
		return;
	fprintf(f, "P6\n%d %d\n%d\n", img->width, img->height, img->max_val);
	for (int i = 0; i < img->height; i++) {
		for (int j = 0; j < img->width; j++) {
			fwrite(&img->pixels[i][j].r, 1, 1, f);
			fwrite(&img->pixels[i][j].g, 1, 1, f);
			fwrite(&img->pixels[i][j].b, 1, 1, f);
		}
	}
	fclose(f);
}

/*
	parse_hex_line - Converts hex string to bytes (for BDF).
	Used to decode the bitmap data for glyphs.
*/
void parse_hex_line(char *line, unsigned char *buffer, int bytes_needed)
{
	char *hex;
	unsigned int val;

	hex = malloc(3 * sizeof(char));
	if (!hex)
		exit(1);

	for (int i = 0; i < bytes_needed; i++) {
		hex[0] = line[i * 2];
		hex[1] = line[i * 2 + 1];
		hex[2] = '\0';
		if (sscanf(hex, "%x", &val) != 1)
			val = 0;
		buffer[i] = (unsigned char)val;
	}
	free(hex);
}

/*
	create_glyph - Allocates a new empty glyph.
*/
glyph *create_glyph(void)
{
	glyph *g = malloc(sizeof(glyph));

	if (!g)
		exit(1);
	g->name = NULL;
	g->bitmap = NULL;
	g->encoding = -1;
	g->dwidth_x = 0;
	g->dwidth_y = 0;
	g->bb_w = 0;
	g->bb_h = 0;
	g->bb_off_x = 0;
	g->bb_off_y = 0;
	return g;
}

/*
	destroy_glyph - Frees memory for a glyph.
*/
void destroy_glyph(glyph *g)
{
	if (!g)
		return;
	if (g->name)
		free(g->name);
	if (g->bitmap)
		free(g->bitmap);
	free(g);
}

/*
	read_bdf_char - Reads one character definition from BDF.
	Parses STARTCHAR ... ENDCHAR block, extracts metrics and bitmap.
*/
void read_bdf_char(FILE *f, font *font, char *first_line)
{
	char *buf, *p;
	glyph *g;
	bool in_bitmap = false;
	int bmap_r = 0, bytes_r = 0;

	buf = malloc(20000 * sizeof(char));
	if (!buf)
		exit(1);

	g = create_glyph();
	p = strchr(first_line, ' ');
	if (p)
		g->name = my_strdup(p + 1);

	while (fgets(buf, 20000, f)) {
		buf[strcspn(buf, "\r\n")] = 0;
		if (strncmp(buf, "ENDCHAR", 7) == 0)
			break;
		if (in_bitmap) {
			if (bmap_r < g->bb_h) {
				parse_hex_line(buf, g->bitmap + (bmap_r * bytes_r), bytes_r);
				bmap_r++;
			}
		} else if (strncmp(buf, "ENCODING", 8) == 0) {
			if (sscanf(buf, "ENCODING %d", &g->encoding) != 1)
				g->encoding = -1;
		} else if (strncmp(buf, "DWIDTH", 6) == 0) {
			if (sscanf(buf, "DWIDTH %d %d", &g->dwidth_x, &g->dwidth_y) != 2) {
				g->dwidth_x = 0;
				g->dwidth_y = 0;
			}
		} else if (strncmp(buf, "BBX", 3) == 0) {
			if (sscanf(buf, "BBX %d %d %d %d",
					   &g->bb_w, &g->bb_h, &g->bb_off_x,
					   &g->bb_off_y) != 4) {
				g->bb_w = 0;
			}
			bytes_r = (g->bb_w + 7) / 8;
			g->bitmap = malloc(bytes_r * g->bb_h);
		} else if (strncmp(buf, "BITMAP", 6) == 0) {
			in_bitmap = true;
		}
	}
	if (g->encoding >= 0 && g->encoding < 256)
		font->glyphs[g->encoding] = g;
	else
		destroy_glyph(g);

	free(buf);
}

/*
	create_font - Allocates a new empty font.
	Pre-allocates the glyphs array for 256 characters.
*/
font *create_font(void)
{
	font *f = malloc(sizeof(font));

	if (!f)
		exit(1);
	f->name = NULL;
	f->char_count = 0;
	f->max_width = 0;
	f->max_height = 0;
	f->glyphs = malloc(256 * sizeof(glyph *));
	if (!f->glyphs)
		exit(1);
	for (int i = 0; i < 256; i++)
		f->glyphs[i] = NULL;
	return f;
}

/*
	destroy_font - Frees memory for a font.
	Iterates through the glyphs array and frees each individual glyph.
*/
void destroy_font(font *f)
{
	if (!f)
		return;
	if (f->name)
		free(f->name);
	if (f->glyphs) {
		for (int i = 0; i < 256; i++) {
			if (f->glyphs[i])
				destroy_glyph(f->glyphs[i]);
		}
		free(f->glyphs);
	}
	free(f);
}

/*
	load_bdf_file - Loads a BDF font from disk.
	Reads global properties and then delegates to read_bdf_char.
*/
font *load_bdf_file(char *filename)
{
	FILE *f;
	char *buf;
	font *font;
	bool in_props = false;

	f = fopen(filename, "r");
	if (!f)
		return NULL;

	buf = malloc(20000 * sizeof(char));
	if (!buf) {
		fclose(f);
		return NULL;
	}

	font = create_font();
	while (fgets(buf, 20000, f)) {
		buf[strcspn(buf, "\r\n")] = 0;
		if (strncmp(buf, "STARTPROPERTIES", 15) == 0) {
			in_props = true;
			continue;
		}
		if (strncmp(buf, "ENDPROPERTIES", 13) == 0) {
			in_props = false;
			continue;
		}
		if (in_props)
			continue;
		if (strncmp(buf, "FONT ", 5) == 0) {
			font->name = my_strdup(buf + 5);
			font->name[strcspn(font->name, "\r\n")] = 0;
		} else if (strncmp(buf, "CHARS ", 6) == 0) {
			font->char_count = atoi(buf + 6);
		} else if (strncmp(buf, "STARTCHAR", 9) == 0) {
			read_bdf_char(f, font, buf);
		}
	}
	free(buf);
	fclose(f);
	return font;
}

/*
	copy_font - Deep copies a font structure.
	Allocates new memory for the font and duplicates all its glyphs.
*/
font *copy_font(font *src)
{
	font *dst;
	int bytes;
	glyph *gs, *gd;

	if (!src)
		return NULL;
	dst = create_font();
	if (src->name)
		dst->name = my_strdup(src->name);
	dst->max_width = src->max_width;
	dst->max_height = src->max_height;
	dst->char_count = src->char_count;

	for (int i = 0; i < 256; i++) {
		if (src->glyphs && src->glyphs[i]) {
			gs = src->glyphs[i];
			gd = create_glyph();
			if (gs->name)
				gd->name = my_strdup(gs->name);
			gd->encoding = gs->encoding;
			gd->dwidth_x = gs->dwidth_x;
			gd->dwidth_y = gs->dwidth_y;
			gd->bb_w = gs->bb_w;
			gd->bb_h = gs->bb_h;
			gd->bb_off_x = gs->bb_off_x;
			gd->bb_off_y = gs->bb_off_y;

			if (gs->bitmap) {
				bytes = ((gs->bb_w + 7) / 8) * gs->bb_h;
				gd->bitmap = malloc(bytes);
				memcpy(gd->bitmap, gs->bitmap, bytes);
			}
			dst->glyphs[i] = gd;
		}
	}
	return dst;
}

/*
	create_copy_of_state - Deep copies the program state.
	Recursively copies the image, rules, and font for Undo/Redo support.
*/
program_state *create_copy_of_state(program_state *source)
{
	program_state *new_state;

	if (!source)
		return NULL;
	new_state = malloc(sizeof(program_state));
	new_state->l_system_string = source->l_system_string ?
									 my_strdup(source->l_system_string) :
									 NULL;
	new_state->img = create_copy_of_image(source->img);
	new_state->axiom = source->axiom ? my_strdup(source->axiom) : NULL;
	new_state->rules_count = source->rules_count;
	if (source->rules_count > 0 && source->rules) {
		new_state->rules = malloc(sizeof(l_rule) * source->rules_count);
		for (int i = 0; i < source->rules_count; i++) {
			new_state->rules[i].symbol = source->rules[i].symbol;
			new_state->rules[i].replacement =
				my_strdup(source->rules[i].replacement);
		}
	} else {
		new_state->rules = NULL;
	}
	new_state->input_file = source->input_file ?
								my_strdup(source->input_file) :
								NULL;
	new_state->font = copy_font(source->font);
	new_state->is_text_last = source->is_text_last;
	return new_state;
}

/*
	destroy_state - Frees a program state.
	Releases all resources attached to a state snapshot.
*/
void destroy_state(program_state *state)
{
	if (!state)
		return;
	if (state->l_system_string)
		free(state->l_system_string);
	if (state->img)
		destroy_image(state->img);
	if (state->axiom)
		free(state->axiom);
	if (state->rules) {
		for (int i = 0; i < state->rules_count; i++)
			free(state->rules[i].replacement);
		free(state->rules);
	}
	if (state->input_file)
		free(state->input_file);
	if (state->font)
		destroy_font(state->font);
	free(state);
}

/*
	push - Pushes a state onto the stack.
*/
void push(stack **top, program_state *new_state)
{
	stack *new_node = malloc(sizeof(stack));

	if (!new_node)
		exit(1);
	new_node->state = new_state;
	new_node->next = *top;
	*top = new_node;
}

/*
	pop - Pops a state from the stack.
*/
program_state *pop(stack **top)
{
	stack *temp;
	program_state *popped_data;

	if (!*top)
		return NULL;
	temp = *top;
	popped_data = temp->state;
	*top = (*top)->next;
	free(temp);
	return popped_data;
}

/*
	is_stack_empty - Checks if the stack is empty.
*/
bool is_stack_empty(stack *top)
{
	if (!top)
		return true;
	return false;
}

/*
	clear_stack - Frees all states in the stack.
*/
void clear_stack(stack **top)
{
	program_state *s;

	while (!is_stack_empty(*top)) {
		s = pop(top);
		destroy_state(s);
	}
}

