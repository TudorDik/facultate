/*
	Basic pixel structure for RGB colors.
	Each component is an unsigned char (0-255).
	Used to represent a single point of color in the image.
*/
typedef struct {
	unsigned char r, g, b;
} pixel;

/*
	Image buffer containing raw pixel data and dimensions.
	- width: The width of the image in pixels.
	- height: The height of the image in pixels.
	- max_val: Maximum color value (usually 255 for standard RGB).
	- pixels: A 2D array of pixel structures representing the image grid.
*/
typedef struct {
	int width, height, max_val;
	pixel **pixels;
} image;

/*
	Glyph structure for BDF fonts.
	Represents a single character in a bitmap font.
	- name: The name of the glyph (e.g., "A", "space").
	- bitmap: The raw binary data representing the pixel pattern.
	- encoding: The ASCII or Unicode value corresponding to this glyph.
	- dwidth: Device Width. The vector (x,y) to move the cursor after drawing.
	This determines the spacing between characters.
	- bb: Bounding Box. The smallest rectangle enclosing the "ink".
	- bb_w, bb_h: Dimensions of the bounding box.
	- bb_off: Offset from cursor position to the bounding box origin.
*/
typedef struct {
	char *name;
	unsigned char *bitmap;
	int encoding;           /* ASCII code */
	int dwidth_x, dwidth_y; /* Vector to move cursor after char */
	int bb_w, bb_h;         /* Width/Height of the bitmap */
	int bb_off_x, bb_off_y; /* Offset from origin */
} glyph;

/*
	Font structure holding an array of glyphs (mapped by ASCII code).
	- name: The name of the font family.
	- glyphs: Array of pointers to glyph structures (index 0-255).
	- max_width, max_height: The max dimensions of any glyph in the font.
	- char_count: The total number of characters defined in the font.
*/
typedef struct {
	char *name;
	glyph **glyphs;         /* Array of pointers to glyphs (index 0-255) */
	int max_width, max_height, char_count;
} font;

/*
	L-System production rule (e.g., F -> F+F-F).
	- symbol: The character that triggers the rule (predecessor).
	- replacement: The string that replaces the symbol (successor).
*/
typedef struct {
	char symbol;
	char *replacement;
} l_rule;

/*
	Program State.
	This structure holds the ENTIRE context of the application at any point.
	It encapsulates everything needed to reconstruct the current drawing state.
	We deep-copy this structure onto the Undo stack before any operation
	that modifies data. This ensures we can revert everything perfectly.
	- l_system_string: Current string generated by derivation (unused).
	- axiom: The starting string for the L-System generation.
	- input_file: Name of the currently loaded file.
	- img: The image canvas we are drawing on.
	- rules: An array of L-System production rules.
	- font: The currently loaded BDF font for text rendering.
	- rules_count: The number of rules in the 'rules' array.
	- is_text_last: Flag to track the last operation type for status messages.
*/
typedef struct {
	char *l_system_string;  /* Current L-system string (deprecated/unused?) */
	char *axiom;            /* The starting string for L-systems */
	char *input_file;       /* Name of the currently loaded file */
	image *img;             /* The canvas we draw on */
	l_rule *rules;          /* Array of production rules */
	font *font;             /* Currently loaded BDF font */
	int rules_count;
	bool is_text_last;      /* Flag to adjust status message output */
} program_state;

/*
	Stack (LIFO) for Undo/Redo history.
	A singly linked list where each node holds a pointer to a `program_state`.
	- state: Pointer to the saved program state.
	- next: Pointer to the next node in the stack.
*/
typedef struct stack {
	program_state *state;
	struct stack *next;
} stack;

/*
	Generic linked list node for the command queue.
	Used to store strings (command tokens).
	- data: The string data stored in this node.
	- next: Pointer to the next node in the list.
*/
typedef struct node {
	char *data;
	struct node *next;
} node;

/*
	Queue (FIFO) for parsing command line arguments.
	Ensures we process arguments (like x, y, color) in the correct order.
	- front: Pointer to the first element (where we dequeue).
	- rear: Pointer to the last element (where we enqueue).
*/
typedef struct {
	node *front, *rear;
} queue;

